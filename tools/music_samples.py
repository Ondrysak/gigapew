#!/usr/bin/env python3
"""Prepare every PROTOKSEED WAV and its explicit Godot dependency catalog.

python tools/music_samples.py "/path/to/PROTOKSEED SAMPLE PACK"
Requires NumPy. Original voice recordings are never modified.

Complete recordings, not selected slices: average stereo PCM16/44100 to mono,
127-tap Hamming/sinc antialias filter, 2:1 decimation, DC removal, peak ceilings,
1 ms boundaries, mono PCM16/22050. Source hashes and exact loop grids are stored
in catalog.gd. Source filenames label kick pitch classes; other roots are unknown.
The supplied pack contains no licence/readme: redistribution remains unverified.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import wave

import numpy as np

RATE = 22050
PITCH_CLASSES = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5,
                 "F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}


def classify(name: str) -> tuple[str, int]:
    kick = re.fullmatch(r"PTKSD - KICK ([A-G]#?) \d+", name)
    if kick:
        return "kick", 36 + PITCH_CLASSES[kick[1]]
    for prefix, role in (("DRUM LOOP", "break"), ("303", "acid"),
                         ("AMBT", "ambient"), ("FX", "fx"),
                         ("KICK FX", "fx"), ("LEAD", "lead")):
        if re.fullmatch(rf"PTKSD - {prefix} \d+", name):
            return role, -1
    raise ValueError(f"Unrecognized sample role: {name}")


def prepare(pack: Path, output: Path) -> None:
    output.mkdir(parents=True, exist_ok=True)
    sources = sorted(pack.rglob("*.wav"))
    if not sources:
        raise ValueError(f"No WAVs in {pack}")
    taps = np.arange(-63, 64, dtype=np.float64)
    kernel = .45 * np.sinc(.45 * taps) * np.hamming(127)
    kernel /= kernel.sum()
    catalog = ["# Generated by tools/music_samples.py; complete recordings, explicit export dependencies.",
               "# Source terms were not supplied; these samples are not CC0.", "const CLIPS := {"]
    ids: set[str] = set()
    counts: dict[str, int] = {}
    total_pcm = 0
    for source in sources:
        role, root = classify(source.stem)
        name = source.stem.removeprefix("PTKSD - ").lower().replace("#", "s").replace(" ", "_")
        if name in ids:
            raise ValueError(f"Duplicate sample id: {name}")
        ids.add(name)
        relative = source.relative_to(pack).as_posix()
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        with wave.open(str(source), "rb") as reader:
            frames = reader.getnframes()
            if (reader.getnchannels(), reader.getsampwidth(), reader.getframerate(),
                    reader.getcomptype()) != (2, 2, 44100, "NONE"):
                raise ValueError(f"Unexpected source WAV format: {source}")
            stereo = np.frombuffer(reader.readframes(frames), dtype="<i2").reshape(-1, 2)
        mono = stereo.astype(np.float64).mean(axis=1) / 32768.0
        samples = np.convolve(np.pad(mono, (63, 63), mode="reflect"), kernel, mode="valid")[::2].copy()
        samples -= samples.mean()
        maximum = float(np.max(np.abs(samples)))
        if maximum == 0.0:
            raise ValueError(f"Silent mono source: {source}")
        samples *= (.94 if role == "kick" else .8) / maximum
        count = min(len(samples) // 2, round(.001 * RATE))
        envelope = np.linspace(0.0, 1.0, count)
        samples[:count] *= envelope
        samples[-count:] *= envelope[::-1]
        pcm = np.rint(np.clip(samples, -1.0, 1.0) * 32767.0).astype("<i2")
        target = output / f"{name}.wav"
        with wave.open(str(target), "wb") as writer:
            writer.setnchannels(1)
            writer.setsampwidth(2)
            writer.setframerate(RATE)
            writer.writeframes(pcm.tobytes())
        resource = f"res://assets/audio/protokseed/{name}.wav"
        imported = f"res://.godot/imported/{name}.wav-{hashlib.md5(resource.encode()).hexdigest()}.sample"
        target.with_suffix(".wav.import").write_text(
            '[remap]\n\nimporter="wav"\ntype="AudioStreamWAV"\n'
            f'path="{imported}"\n\n[deps]\n\nsource_file="{resource}"\n'
            f'dest_files=["{imported}"]\n\n[params]\n\n'
            'force/8_bit=false\nforce/mono=true\nforce/max_rate=false\n'
            'force/max_rate_hz=22050\nedit/trim=false\nedit/normalize=false\n'
            'edit/loop_mode=0\nedit/loop_begin=0\nedit/loop_end=-1\ncompress/mode=0\n',
            encoding="utf-8",
        )
        beats = 0
        bpm = 0.0
        if role in ("break", "acid", "lead"):
            beats = round(frames / 44100.0 * 170.0 / 60.0)
            error = abs(frames / 44100.0 - beats * 60.0 / 170.0)
            if beats <= 0 or error > 1.0 / RATE:
                raise ValueError(f"Source is not on the measured 170 BPM grid: {source}")
            # Actual converted frame count, including odd-source-frame rounding.
            bpm = beats * 60.0 * RATE / len(pcm)
        catalog.append(f'\t&"{name}": {{"stream": preload("{resource}"), "role": &"{role}", '
                       f'"source": "{relative}", "source_sha256": "{digest}", '
                       f'"root": {root}, "bpm": {bpm:.9f}, "beats": {beats}.0}},')
        counts[role] = counts.get(role, 0) + 1
        total_pcm += pcm.nbytes
        print(f"{name}: {len(pcm)} frames, role={role}, source SHA256={digest}")
    catalog.append("}\n")
    (output / "catalog.gd").write_text("\n".join(catalog), encoding="utf-8")
    print(f"Prepared {len(ids)} complete WAVs: {counts}; {total_pcm} PCM bytes. Licence permission unverified.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pack", type=Path, help="Local PROTOKSEED SAMPLE PACK directory")
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "assets/audio/protokseed")
    arguments = parser.parse_args()
    prepare(arguments.pack, arguments.output)
