#!/usr/bin/env python3
"""Convert a curated, key-matched TECHNO_ESS selection for the game.

Usage: python3 tools/techno_samples.py /path/to/TECHNO_ESS
Requires NumPy. Originals stay untouched. Complete 24-bit stereo/44100 WAVs
become mono PCM16/22050 using the same 127-tap antialias filter and 1 ms edges
as music_samples.py. The catalog preserves source hashes, keys and loop grids.
No redistribution licence was found in the supplied pack; these are not CC0.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import wave

import numpy as np

RATE = 22050
# C minor, Eb minor and Gb minor each have bass, synth, arp and atmosphere.
LOOPS = {
    "BASSLOOPS_125BPM": ("bass", {1, 2, 3, 5, 8, 12, 16}),
    "SYNTH_LOOPS_125BPM": ("synth", {12, 14, 18, 36, 38}),
    "ARP_LOOPS_125BPM": ("arp", {2, 14, 21, 29, 31}),
    "EFX_ATMOS_HITS_LOOPS_125BPM": ("ambient", {1, 7, 8}),
}
PITCHES = {"C": 0, "Db": 1, "D": 2, "Eb": 3, "E": 4, "F": 5,
           "Gb": 6, "G": 7, "Ab": 8, "A": 9, "Bb": 10, "B": 11}


def selection(pack: Path) -> list[tuple[Path, str, int, int]]:
    result = []
    for folder, (role, numbers) in LOOPS.items():
        found = set()
        for path in sorted((pack / folder).glob("*.wav")):
            match = re.search(r"_(\d+)_125bpm_([A-G]b?)m\.wav$", path.name)
            if match and int(match[1]) in numbers:
                number = int(match[1])
                result.append((path, role, number, 36 + PITCHES[match[2]]))
                found.add(number)
        if found != numbers:
            raise ValueError(f"Missing {role} loops: {numbers - found}")
    for number in range(1, 13):
        result.append((pack / "DRUMLOOPS_125BPM" /
                       f"TA_TECHNO_DRUMLOOP_{number:02}_NO_KICK_125BPM.wav",
                       "groove", number, -1))
    for role, folder in (("kick", "KICKS"), ("clap", "CLAPS_SNARES"),
                         ("hat", "HATS_RIDES")):
        for number in range(1, 9):
            result.append((pack / "SINGLE_HITS" / folder /
                           f"TA_TECHNO_{role.upper()}_{number:02}.wav",
                           role, number, -1))
    return result


def prepare(pack: Path, output: Path) -> None:
    sources = selection(pack)
    output.mkdir(parents=True, exist_ok=True)
    taps = np.arange(-63, 64, dtype=np.float64)
    kernel = .45 * np.sinc(.45 * taps) * np.hamming(127)
    kernel /= kernel.sum()
    catalog = ["# Generated by tools/techno_samples.py; complete recordings and export dependencies.",
               "# TECHNO_ESS source terms unverified; these samples are not CC0.",
               "const CLIPS := {"]
    total_pcm = 0
    counts: dict[str, int] = {}
    for source, role, number, root in sources:
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        with wave.open(str(source), "rb") as reader:
            frames = reader.getnframes()
            if (reader.getnchannels(), reader.getsampwidth(), reader.getframerate(),
                    reader.getcomptype()) != (2, 3, 44100, "NONE"):
                raise ValueError(f"Expected stereo PCM24/44100: {source}")
            triples = np.frombuffer(reader.readframes(frames), dtype=np.uint8).reshape(-1, 3)
        values = (triples[:, 0].astype(np.int32) |
                  triples[:, 1].astype(np.int32) << 8 |
                  triples[:, 2].astype(np.int32) << 16)
        signed = (values ^ 0x800000) - 0x800000
        mono = signed.reshape(-1, 2).mean(axis=1) / 8388608.0
        samples = np.convolve(np.pad(mono, (63, 63), mode="reflect"), kernel,
                              mode="valid")[::2].copy()
        samples -= samples.mean()
        maximum = float(np.max(np.abs(samples)))
        if maximum == 0:
            raise ValueError(f"Silent mono source: {source}")
        samples *= (.94 if role == "kick" else .8) / maximum
        count = min(len(samples) // 2, round(.001 * RATE))
        envelope = np.linspace(0.0, 1.0, count)
        samples[:count] *= envelope
        samples[-count:] *= envelope[::-1]
        pcm = np.rint(np.clip(samples, -1.0, 1.0) * 32767).astype("<i2")
        name = f"techno_{role}_{number:02}"
        target = output / f"{name}.wav"
        with wave.open(str(target), "wb") as writer:
            writer.setnchannels(1)
            writer.setsampwidth(2)
            writer.setframerate(RATE)
            writer.writeframes(pcm.tobytes())
        resource = f"res://assets/audio/techno/{name}.wav"
        imported = f"res://.godot/imported/{name}.wav-{hashlib.md5(resource.encode()).hexdigest()}.sample"
        target.with_suffix(".wav.import").write_text(
            '[remap]\n\nimporter="wav"\ntype="AudioStreamWAV"\n'
            f'path="{imported}"\n\n[deps]\n\nsource_file="{resource}"\n'
            f'dest_files=["{imported}"]\n\n[params]\n\n'
            'force/8_bit=false\nforce/mono=true\nforce/max_rate=false\n'
            'force/max_rate_hz=22050\nedit/trim=false\nedit/normalize=false\n'
            'edit/loop_mode=0\nedit/loop_begin=0\nedit/loop_end=-1\ncompress/mode=0\n',
            encoding="utf-8")
        beats = 0
        bpm = 0.0
        if role not in ("kick", "clap", "hat"):
            beats = round(frames / 44100 * 125 / 60)
            if beats <= 0 or abs(frames / 44100 - beats * 60 / 125) > 1 / RATE:
                raise ValueError(f"Loop is not on the 125 BPM grid: {source}")
            bpm = beats * 60 * RATE / len(pcm)
        catalog.append(f'\t&"{name}": {{"stream": preload("{resource}"), "role": &"{role}", '
                       f'"source": "{source.relative_to(pack).as_posix()}", "source_sha256": "{digest}", '
                       f'"root": {root}, "bpm": {bpm:.9f}, "beats": {beats}.0}},')
        total_pcm += pcm.nbytes
        counts[role] = counts.get(role, 0) + 1
    catalog.append("}\n")
    (output / "catalog.gd").write_text("\n".join(catalog), encoding="utf-8")
    print(f"Prepared {len(sources)} complete WAVs: {counts}; {total_pcm} PCM bytes. Source terms unverified.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pack", type=Path)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "assets/audio/techno")
    arguments = parser.parse_args()
    prepare(arguments.pack, arguments.output)
